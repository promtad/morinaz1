export function tr(locale: Locale, key: string): string {
  const entry = dict[key];
  if (!entry) return key;
  return entry[locale];
}

export function pick<T extends { nameAr: string; nameEn: string }>(locale: Locale, item: T): string {
  return locale === "en" ? item.nameEn : item.nameAr;
}
